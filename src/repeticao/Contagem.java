package repeticao;

/*
 * Exercício: Contagem de 1 a 10
 * Objetivo: Imprimir os números de 1 até 10.
 * Conceitos: for loop (estrutura de repetição).
 */
public class Contagem {
    static void main(String[] args) {

        /*
         * for loop: estrutura de repetição com três partes:
         * 1. int i = 1: inicialização (começa em 1)
         * 2. i <= 10: condição (executa enquanto i for menor ou igual a 10)
         * 3. i++: incremento (aumenta i em 1 a cada repetição)
         */
        for (int i = 1; i <= 10; i++) {

            System.out.println(i);
        }


    }
}
